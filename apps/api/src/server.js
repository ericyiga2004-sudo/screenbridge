import 'dotenv/config';
import express from 'express';
import http from 'node:http';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {Server} from 'socket.io';
import {connectOptionalDatabase} from './db.js';
import {registerSessions} from './sessions.js';
const app=express();
const origin=process.env.WEB_ORIGIN || 'http://localhost:5173';
const allowed=process.env.NODE_ENV!=='production' ? true : origin.split(',').map(x=>x.trim());
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:false,crossOriginEmbedderPolicy:false}));
app.use(cors({origin:allowed}));
app.use(express.json({limit:'16kb'}));
app.use('/api',rateLimit({windowMs:60_000,limit:120,standardHeaders:'draft-7',legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({ok:true,app:'ScreenBridge',timestamp:new Date().toISOString()}));
app.get('/api/ice-config',(_req,res)=>{
 const urls=String(process.env.TURN_URLS||'').split(',').map(v=>v.trim()).filter(Boolean);
 const iceServers=[{urls:['stun:stun.l.google.com:19302','stun:stun1.l.google.com:19302']}];
 if(urls.length&&process.env.TURN_USERNAME&&process.env.TURN_CREDENTIAL)iceServers.push({urls,username:process.env.TURN_USERNAME,credential:process.env.TURN_CREDENTIAL});
 res.set('Cache-Control','no-store');res.json({iceServers,turnConfigured:iceServers.length>1});
});
app.use((err,_req,res,_next)=>{console.error('API error:',err);res.status(500).json({error:'Unexpected server error'});});
const httpServer=http.createServer(app);
const io=new Server(httpServer,{path:'/socket.io',cors:{origin:allowed,methods:['GET','POST']},maxHttpBufferSize:128_000,pingTimeout:20000});
registerSessions(io);
const PORT=Number(process.env.PORT)||4000;
await connectOptionalDatabase();
httpServer.listen(PORT,'0.0.0.0',()=>console.log(`ScreenBridge API ready: http://localhost:${PORT}`));
